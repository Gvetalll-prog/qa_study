# Программа расчета возраста для QA
print("--- Проверка возраста пользователя ---")

year_input = input("Введи год твоего рождения: ")

# Превращаем текст в целое число (Integer)
birth_year = int(year_input)

# Текущий год (поставим 2026, как в системе)
current_year = 2026

age = current_year - birth_year

print(f"Сейчас тебе {age} лет.")

if birth_year > current_year:
    # Случай 1: Год из будущего
    print("Ошибка! Ты еще не родился, путешественник во времени! 🚀")

elif age < 18:
    # Случай 2: Слишком молод (используем elif - "а если")
    print(f"Тебе всего {age}. Приходи учиться через {18 - age} лет.")

elif age > 100:
    # Случай 3: Слишком стар (для примера)
    print(f"Ого, тебе {age}! Учиться никогда не поздно, но проверь год рождения.")

else:
    # Случай 4: Все остальные варианты (от 18 до 100)
    print(f"Тебе {age} лет. Доступ к курсу QA разрешен! ✅")
    